#!/usr/bin/env python3
"""Write docs/ECONOMICS.md from measured numbers only.

    python3 scripts/economics.py [--check]

Inputs: runs/gas.json (gas per step, measured on a local node by
`make gas`) and web/swarm-wash.json (what the washed storm cost and earned,
from `make swarm-seeds STORM=6 WASH=1`). Gas is turned into NEAR at the
protocol's minimum gas price (100,000,000 yoctoNEAR per gas, i.e. 0.0001 NEAR
per Tgas), which is what testnet and mainnet charge when blocks are not full.
No market prices are assumed: dollar figures are given as a break-even NEAR
price instead.

--check  fail if docs/ECONOMICS.md differs from what the inputs give.
"""
import json
import sys

GAS_PRICE = 100_000_000  # yoctoNEAR per gas (NEAR's minimum gas price)
YOCTO = 10**24


def near(gas):
    return gas * GAS_PRICE / YOCTO


def tg(gas):
    return gas / 10**12


g = json.load(open("runs/gas.json"))["steps"]
w = json.load(open("web/swarm-wash.json"))["mean"]

rows = [
    ("Post a job (factory creates the job account)", "post_job"),
    ("Open a bid slot", "open_bids"),
    ("One bid", "bid"),
    ("`award_best`, 4 bidders (reads 4 records)", "award_best_4_bidders"),
    ("`award_best`, 16 bidders, 16-payer list", "award_best_16_bidders_16_payers"),
    ("Deliver (signature check)", "deliver"),
    ("Submit the signed judge answer", "submit_check"),
    ("Close the check round", "finalize_check"),
    ("Approve", "approve"),
    ("Settle, pay, delete the sub-job", "settle_and_delete_sub_job"),
]
part = g["whole_part_plain"]
part_i = g["whole_part_via_intents"]
min_part = near(part) * 100  # on-chain cost is 1% of the part's price

plain, listed = w["records"], w["records+allowlist"]


def breakeven(r):
    # NEAR price (in fUSD) at which the wash costs as much as it earns.
    return (r["storm earned fUSD"] - r["wash fUSD outlay"]) / r["wash NEAR spent"]


out = f"""# Unit economics

Generated by `scripts/economics.py` from measured numbers only:
`runs/gas.json` (`make gas`: one local-node run that times every step of a
part's life) and `web/swarm-wash.json` (the washed-storm runs). Gas is priced
at NEAR's minimum gas price, 0.0001 NEAR per Tgas, which is what testnet and
mainnet charge when blocks are not full. fUSD is test USD (1 fUSD = 1 USD of
the token's own units). No NEAR market price is assumed: where one matters,
the table gives the NEAR price at which the result flips.

## Gas per step

| Step | Tgas | NEAR |
|---|---|---|
""" + "".join(f"| {name} | {tg(g[k]):.1f} | {near(g[k]):.5f} |\n" for name, k in rows) + f"""
**One whole part** (post, hire, deliver, signed check, approve, settle, both
accounts deleted; {g['whole_part_plain_txs']} transactions): **{tg(part):.1f} Tgas = {near(part):.4f} NEAR**.
Paid out through the NEAR Intents Verifier instead ({g['whole_part_via_intents_txs']} transactions): {tg(part_i):.1f} Tgas
= {near(part_i):.4f} NEAR, so the Intents leg adds {tg(part_i - part):.1f} Tgas.

Storage comes back: each job account holds about 0.035 NEAR while it
lives and returns it when it deletes; a bid holds 0.001 NEAR until the
slot closes; a client prepays 0.06 NEAR per post. The one fixed cost is the
global job contract, deployed once per network (about 29 testnet NEAR).

## What size of work this fits

On-chain cost stays under 1% of the price for any part worth more than
**{min_part:.2f} NEAR** (100 x {near(part):.4f}). Below that, batch several parts into one job
or keep them off-chain. A sub-part bought by a contractor adds one account
and its own deliver, check and settle, roughly the same cost again.

## Who earns

| Who | How | Set by |
|---|---|---|
| Protocol (factory owner) | platform fee on every posted budget, only when the post succeeds | 0.5% in the swarm; the contract caps it at 1% |
| Lead agent | lead fee, earned pro rata to the parts that are paid (a lead whose parts all fail gets none); the Dutch auction on signed job offers makes leads compete the cap down | per job, `max_lead_fee` in the client's offer |
| Contractor | margin between what it won and what it pays its sub-workers | the contract makes its sub-budget less than its pay |
| Solver | spread on swapping a worker's pay in the NEAR Intents Verifier | the solver's own quote |
| Lead's treasury | 1% for buying a checked worker's payout early (Job Note) | per note |

## What an attack costs

The washed storm: before attacking, sybil managers pay their own sybils
through real factory jobs so each sybil crosses the trusted line. Per run,
mean of 4 seeds:

| | Plain records | Records + payer list |
|---|---|---|
| Washing cost, fUSD (platform fees) | {plain['wash fUSD outlay']:.2f} | {listed['wash fUSD outlay']:.2f} |
| Washing cost, NEAR (gas and storage) | {plain['wash NEAR spent']:.2f} | {listed['wash NEAR spent']:.2f} |
| Earned by the storm, fUSD | {plain['storm earned fUSD']:.2f} | {listed['storm earned fUSD']:.2f} |
| The attack loses money once 1 NEAR is worth more than | {breakeven(plain):.2f} fUSD | {breakeven(listed):.2f} fUSD |

Against plain records the attack pays unless NEAR is worth more than
{breakeven(plain):.2f} fUSD. Against buyers with a payer list it loses money once NEAR
is worth more than about {breakeven(listed):.2f} fUSD, and every fresh sybil has to be
washed again.

## First adopters and the calls they make

| Who | What they call |
|---|---|
| A multi-agent pipeline on NEAR AI Cloud (one agent splits a task and pays others) | `post_job` (or a signed job offer), `open_bids` / `award_best`, workers `deliver` with the NEAR AI receipt, `settle` |
| An agent marketplace that wants escrow without holding funds | the factory as its settlement layer: one `ft_transfer_call` per job, `get_record_from` for its own trust list ([INTEGRATE.md](INTEGRATE.md)) |
| A worker agent paid in another asset | `payout_via` = the NEAR Intents Verifier, then a signed `token_diff` with any solver and `ft_withdraw` |
"""

if "--check" in sys.argv:
    ok = open("docs/ECONOMICS.md").read() == out
    print(("ok  " if ok else "FAIL"), "docs/ECONOMICS.md matches runs/gas.json and web/swarm-wash.json")
    sys.exit(0 if ok else 1)
open("docs/ECONOMICS.md", "w").write(out)
print(f"wrote docs/ECONOMICS.md: one part {tg(part):.1f} Tgas = {near(part):.4f} NEAR")
